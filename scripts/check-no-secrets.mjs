import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const skip = new Set(["node_modules", ".git", ".wrangler", "dist", "package-lock.json"]);
const appId = /cli_[0-9a-f]{16}/i;
const hex32 = /\b[0-9a-f]{32}\b/i;
const workersDev = /\b(?!example\.workers\.dev\b)[a-z0-9-]+\.workers\.dev\b/i;
const openId = /ou_[0-9a-f]{20,}/i;
const docToken = /\b[A-Za-z0-9]{27}\b/;
const secretKeys = [
  "FEISHU_APP_ID",
  "FEISHU_APP_SECRET",
  "COOKIE_SECRET",
  "OWNER_OPEN_ID",
  "MCP_DISABLED",
  "TOOL_BACKENDS",
  "P2P_DISCOVERY",
];

export function scanTree(root) {
  const normalized = root.replace(/[\\/]+$/, "");
  const failures = [];
  walk(normalized, normalized, failures);
  return failures;
}

function walk(root, dir, failures) {
  for (const name of readdirSync(dir)) {
    if (skip.has(name)) continue;
    const path = join(dir, name);
    const stat = statSync(path);
    if (stat.isDirectory()) {
      walk(root, path, failures);
      continue;
    }
    if (!stat.isFile() || stat.size > 2_000_000) continue;
    const text = readFileSync(path, "utf8");
    const rel = relative(root, path);
    collect(rel, text, failures);
  }
}

function collect(path, text, failures) {
  const scanned = text.replace(
    /\/\/ Generated by Wrangler by running `wrangler types` \(hash: [0-9a-f]{32}\)/i,
    "",
  );
  if (appId.test(scanned)) failures.push(`${path} contains a Feishu app id`);
  if (hex32.test(scanned)) failures.push(`${path} contains a 32-hex id`);
  if (workersDev.test(scanned)) failures.push(`${path} contains a non-placeholder workers.dev host`);
  if (openId.test(scanned)) failures.push(`${path} contains a long open_id`);
  if (path.split(/[\\/]/).includes("fixtures") && path.includes(`${join("test", "fixtures")}`) && docToken.test(text)) {
    failures.push(`${path} contains a 27-character doc token`);
  }
  if (path.endsWith("wrangler.jsonc")) {
    if (text.includes('"account_id"')) failures.push(`${path} contains account_id`);
    if (/"id"\s*:/.test(text)) failures.push(`${path} contains a KV id`);
    for (const key of secretKeys) {
      if (text.includes(`"${key}"`)) failures.push(`${path} must not declare secret ${key}`);
    }
  }
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll("\\", "/"));
if (isMain) {
  const root = new URL("..", import.meta.url).pathname;
  const failures = scanTree(root);
  if (failures.length > 0) {
    console.error(failures.join("\n"));
    process.exit(1);
  }
}
